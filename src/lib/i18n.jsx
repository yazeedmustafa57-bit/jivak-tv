// ---------- Provider & Hook ----------

const I18nContext = createContext(null)

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(detectInitialLang)

  useEffect(() => {
    const meta = LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0]
    document.documentElement.lang = meta.code
    document.documentElement.dir = meta.dir
    try {
      localStorage.setItem(STORAGE_KEY, lang)
    } catch {
      /* ignore */
    }
    // Sprache in der URL mitsynchronisieren (?lang=...), damit Links
    // teilbar sind und Suchmaschinen sprachspezifische URLs sehen.
    try {
      const url = new URL(window.location.href)
      if (url.searchParams.get('lang') !== lang) {
        url.searchParams.set('lang', lang)
        window.history.replaceState(window.history.state, '', url.toString())
      }
    } catch {
      /* ignore */
    }
  }, [lang])

  const value = useMemo(() => {
    const dict = T[lang] || T.ar
    const fallback = T.ar
    const t = (key, vars) => {
      let str = dict[key] ?? fallback[key] ?? key
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          str = String(str).split('{' + k + '}').join(String(v))
        }
      }
      return str
    }
    const tc = (key, count) => {
      const n = Number(count) || 0
      const sub = n === 1 ? '.one' : '.other'
      return n + ' ' + (dict[key + sub] ?? fallback[key + sub] ?? '')
    }
    const tCategory = (cat) => {
      if (!cat) return ''
      const map = CATEGORY_T[cat.id]
      if (!map) return cat.name || ''
      return map[lang] || map.ar || cat.name
    }
    const tArticle = (article) => {
      if (!article) return article
      const tr = ARTICLE_T[article.id]?.[lang]
      if (!tr) return article
      return {
        ...article,
        title: tr.title,
        intro: tr.intro,
        body: tr.body,
        author: tr.author || { ar: 'تحرير ROJ TV', ku: 'دەستەیا نڤیسینا ROJ TV', en: 'ROJ TV Editorial Team', de: 'Redaktion ROJ TV' }[lang]
      }
    }
    const SEED_AUTHOR_IDS = new Set(['author-redaktion'])
    const tAuthor = (author) => {
      if (!author) return author
      if (!SEED_AUTHOR_IDS.has(author.id)) return author
      return { ...author, role: t('authors.redaktionRole'), bio: t('authors.redaktionBio') }
    }
    const locale = lang === 'ar' ? 'ar-u-nu-latn' : lang
    const safeDate = (ts) => {
      const d = new Date(ts == null ? Date.now() : ts)
      return Number.isNaN(d.getTime()) ? new Date() : d
    }
    // Intl-Fallbacks: Falls eine Locale auf einem Gerät nicht verfügbar ist
    // (eingeschränkte ICU-Daten), fällt der Parser auf eine sichere Locale
    // zurück – ein Locale-Fehler darf nie einen Render crashen.
    const safeLocale = (primary, fallback) => {
      try {
        Intl.DateTimeFormat(primary)
        return primary
      } catch {
        return fallback
      }
    }
    const fmtLocale = safeLocale(locale, lang === 'ar' || lang === 'ku' ? 'en' : locale === 'en' ? 'en' : 'de')
    const fmtDate = (opts, ts) => {
      try {
        return new Intl.DateTimeFormat(fmtLocale, opts).format(safeDate(ts))
      } catch {
        try {
          return new Intl.DateTimeFormat('en-GB', opts).format(safeDate(ts))
        } catch {
          return String(safeDate(ts))
        }
      }
    }
    const formatDate = (ts) => fmtDate({ day: 'numeric', month: 'long', year: 'numeric' }, ts)
    const formatDateTime = (ts) =>
      fmtDate({ day: '2-digit', month: '2-digit', year: 'numeric', hour: '2-digit', minute: '2-digit' }, ts)
    const formatViews = (n) => {
      try {
        return new Intl.NumberFormat(fmtLocale, { notation: 'compact', maximumFractionDigits: 1 }).format(Number(n) || 0)
      } catch {
        return String(Number(n) || 0)
      }
    }
    // Ziffern lokalisieren: Arabisch & Kurdisch (Badini) verwenden die
    // arabisch-indischen Ziffern (٠-٩), Deutsch & Englisch lateinische (0-9).
    const ARABIC_DIGITS = '٠١٢٣٤٥٦٧٨٩'
    const formatNum = (n) => {
      const s = String(n ?? '')
      if (lang !== 'ar' && lang !== 'ku') return s
      return s.replace(/[0-9]/g, (d) => ARABIC_DIGITS[Number(d)])
    }
    return { lang, setLang, t, tc, tCategory, tArticle, tAuthor, formatDate, formatDateTime, formatViews, formatNum }
  }, [lang])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n muss innerhalb des I18nProvider verwendet werden.')
  return ctx
}
