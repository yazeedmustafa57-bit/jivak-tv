export const LANGUAGES = [
  { code: 'ar', label: 'العربية', dir: 'rtl' },
  { code: 'ku', label: 'کوردی', dir: 'rtl' },
  { code: 'en', label: 'English', dir: 'ltr' },
  { code: 'de', label: 'Deutsch', dir: 'ltr' }
]

const STORAGE_KEY = 'jivak.lang'
const DEFAULT_LANG = 'ar'

// Sprache des Browsers erkennen (nur wenn keine gespeicherte/URL-Sprache existiert).
function langFromNavigator() {
  try {
    const raw = String(navigator.language || (navigator.languages && navigator.languages[0]) || '').toLowerCase()
    const base = raw.split('-')[0]
    if (LANGUAGES.some((l) => l.code === base)) return base
    if (raw.includes('ku') || raw === 'ckb') return 'ku'
  } catch {
    /* ignore */
  }
  return null
}

export function detectInitialLang() {
  try {
    const params = new URLSearchParams(window.location.search)
    const fromUrl = params.get('lang')
    if (fromUrl && LANGUAGES.some((l) => l.code === fromUrl)) return fromUrl
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved && LANGUAGES.some((l) => l.code === saved)) return saved
    return langFromNavigator() || DEFAULT_LANG
  } catch {
    return DEFAULT_LANG
  }
}

